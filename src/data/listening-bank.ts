export const LISTENING_BANK = scripts.map(
  ([lessonId, number, title, transcript, translation, question, choices]) => {
    const correct = choices[0]!;
    const options = [...choices.slice(1)];
    const correctIndex = (lessonId + number) % 4;
    options.splice(correctIndex, 0, correct);
    return ListeningPassageSchema.parse({
      id: `listen-${lessonId}-${number}`,
      lessonId,
      title,
      transcript,
      translation,
      playback: 'browser-tts',
      sourceType: 'authored',
      reviewStatus: 'pending',
      questions: [
        { id: `lq_${lessonId}_${number}_1`, question, options, correctIndex, evidence: transcript },
      ],
    });
  },
);
